# Generates crates/core/src/unicode_tables.rs: general-category range tables
# backing the Data.Char ports in crates/core/src/unicode.rs.
# Usage: python3 -I crates/core/tools/gen_unicode_tables.py > crates/core/src/unicode_tables.rs
import sys
import unicodedata

TABLES = [
    ("UPPER", "`isUpper`: Lu | Lt", {"Lu", "Lt"}),
    ("LOWER", "`isLower`: Ll", {"Ll"}),
    ("ALPHA", "`isAlpha`: L*", {"Lu", "Ll", "Lt", "Lm", "Lo"}),
    ("NUMBER", "`isNumber`: N*", {"Nd", "Nl", "No"}),
]


def ranges(cats):
    out = []
    start = None
    for cp in range(0x110000 + 1):
        inside = cp <= 0x10FFFF and unicodedata.category(chr(cp)) in cats
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


w = sys.stdout.write
w("// SPDX-License-Identifier: GPL-3.0-or-later\n")
w("// @generated by crates/core/tools/gen_unicode_tables.py from Unicode %s.\n" % unicodedata.unidata_version)
w("// Do not edit by hand.\n\n")
w("pub const UNICODE_VERSION: &str = \"%s\";\n\n" % unicodedata.unidata_version)
for name, doc, cats in TABLES:
    rs = ranges(cats)
    w("/// %s (inclusive ranges, sorted).\n" % doc)
    w("pub(crate) static %s: &[(u32, u32)] = &[\n" % name)
    for lo, hi in rs:
        w("    (0x%X, 0x%X),\n" % (lo, hi))
    w("];\n\n")
