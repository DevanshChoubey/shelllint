/// Name prefixes of parameter families a zsh theme or plugin gives meaning to.
pub const ZSH_SPECIAL_VARIABLE_PREFIXES: &[&str] = &["ZSH_THEME_"];

/// `name` is a zsh special parameter, or belongs to a special family.
pub fn is_zsh_special_variable(name: &str) -> bool {
    ZSH_SPECIAL_VARIABLES.contains(&name) || ZSH_SPECIAL_VARIABLE_PREFIXES.iter().any(|p| name.starts_with(p))
}

/// Functions the shell calls by name (zshmisc, "Hook Functions" and "Trap
/// Functions"). A `TRAP` function is `TRAPINT`, `TRAPZERR`, `TRAPEXIT` and so on.
pub const ZSH_HOOK_FUNCTIONS: &[&str] =
    &["chpwd", "periodic", "precmd", "preexec", "zshaddhistory", "zshexit", "zsh_directory_name"];

/// `name` is invoked by the shell without an explicit call: a hook function or a `TRAPxxx` function.
pub fn is_zsh_implicit_function(name: &str) -> bool {
    ZSH_HOOK_FUNCTIONS.contains(&name) || name.strip_prefix("TRAP").is_some_and(|s| !s.is_empty())
}

/// `name` is one of the `<hook>_functions` arrays, whose elements the shell calls.
pub fn is_zsh_hook_array(name: &str) -> bool {
    name.strip_suffix("_functions").is_some_and(|h| ZSH_HOOK_FUNCTIONS.contains(&h))
}

