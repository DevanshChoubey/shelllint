// `--completions=bash|zsh|fish` (an extension beyond ShellCheck): print a shell
// completion script generated from the real option table in `options.rs`, so a
// new flag shows up in the scripts without touching this file.

use crate::options::{ArgDescr, FORMAT_NAMES, OptDescr, options};

pub const SHELL_NAMES: [&str; 3] = ["bash", "zsh", "fish"];

const PROG: &str = "shelllint";

/// What can follow an option, keyed by its long name.
enum Values {
    /// A fixed list of words.
    Words(Vec<&'static str>),
    /// A file path.
    File,
    /// A directory.
    Dir,
    /// Nothing useful to offer.
    Free,
}

fn values_for(d: &OptDescr) -> Values {
    match d.longs.first().copied().unwrap_or("") {
        "shell" => Values::Words(vec!["sh", "bash", "dash", "ksh", "busybox"]),
        "format" => Values::Words(FORMAT_NAMES.to_vec()),
        "severity" => Values::Words(vec!["error", "warning", "info", "style"]),
        "color" => Values::Words(vec!["auto", "always", "never"]),
        "extended-analysis" => Values::Words(vec!["true", "false"]),
        "completions" => Values::Words(SHELL_NAMES.to_vec()),
        "rcfile" | "files-from" => Values::File,
        "source-path" => Values::Dir,
        _ => Values::Free,
    }
}

/// The script for `shell`, or `None` when it is not one of `SHELL_NAMES`.
pub fn generate(shell: &str) -> Option<String> {
    let opts = options();
    match shell {
        "bash" => Some(bash(&opts)),
        "zsh" => Some(zsh(&opts)),
        "fish" => Some(fish(&opts)),
        _ => None,
    }
}

fn takes_arg(d: &OptDescr) -> bool {
    !matches!(d.arg, ArgDescr::No(_))
}

fn bash(opts: &[OptDescr]) -> String {
    let mut all_flags = vec![];
    let mut cases = String::new();
    for d in opts {
        let mut names: Vec<String> = d.shorts.chars().map(|c| format!("-{}", c)).collect();
        names.extend(d.longs.iter().map(|l| format!("--{}", l)));
        all_flags.extend(names.iter().cloned());
        if !takes_arg(d) {
            continue;
        }
        let action = match values_for(d) {
            Values::Words(w) => format!("COMPREPLY=( $(compgen -W \"{}\" -- \"$cur\") )", w.join(" ")),
            Values::File => "COMPREPLY=( $(compgen -f -- \"$cur\") )".to_string(),
            Values::Dir => "COMPREPLY=( $(compgen -d -- \"$cur\") )".to_string(),
            Values::Free => "COMPREPLY=()".to_string(),
        };
        cases.push_str(&format!("        {})\n            {}\n            return 0\n            ;;\n", names.join("|"), action));
    }
    format!(
        "# bash completion for {prog}, generated by `{prog} --completions=bash`.\n\
         _{prog}() {{\n\
         \x20   local cur prev\n\
         \x20   cur=\"${{COMP_WORDS[COMP_CWORD]}}\"\n\
         \x20   prev=\"${{COMP_WORDS[COMP_CWORD-1]}}\"\n\
         \x20   # '=' is a word break: for --opt=val, cur is \"=\" or val and prev is \"=\".\n\
         \x20   if [[ \"$cur\" == \"=\" ]]; then\n\
         \x20       prev=\"${{COMP_WORDS[COMP_CWORD-1]}}\"\n\
         \x20       cur=\"\"\n\
         \x20   elif [[ \"$prev\" == \"=\" ]]; then\n\
         \x20       prev=\"${{COMP_WORDS[COMP_CWORD-2]}}\"\n\
         \x20   fi\n\
         \x20   case \"$prev\" in\n\
         {cases}\
         \x20   esac\n\
         \x20   if [[ \"$cur\" == -* ]]; then\n\
         \x20       COMPREPLY=( $(compgen -W \"{flags}\" -- \"$cur\") )\n\
         \x20       return 0\n\
         \x20   fi\n\
         \x20   COMPREPLY=( $(compgen -f -- \"$cur\") )\n\
         }}\n\
         complete -o filenames -F _{prog} {prog}\n",
        prog = PROG,
        cases = cases,
        flags = all_flags.join(" "),
    )
}

/// Escape for a single-quoted zsh word.
fn zsh_quote(s: &str) -> String {
    s.replace('\'', "'\\''")
}

/// Escape for the `[description]` part of an `_arguments` spec.
fn zsh_desc(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if matches!(c, '[' | ']' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Escape for the message part of an `_arguments` spec (colons separate parts).
fn zsh_msg(s: &str) -> String {
    s.replace('\\', "\\\\").replace(':', "\\:")
}

fn zsh(opts: &[OptDescr]) -> String {
    let mut specs = vec![];
    for d in opts {
        let desc = zsh_desc(d.desc);
        let msg = zsh_msg(d.placeholder);
        let action = match values_for(d) {
            Values::Words(w) => format!("({})", w.join(" ")),
            Values::File => "_files".to_string(),
            Values::Dir => "_files -/".to_string(),
            Values::Free => " ".to_string(),
        };
        for c in d.shorts.chars() {
            let spec = match d.arg {
                ArgDescr::No(_) => format!("-{}[{}]", c, desc),
                ArgDescr::Req(_) => format!("-{}+[{}]:{}:{}", c, desc, msg, action),
                ArgDescr::Opt(..) => format!("-{}-[{}]::{}:{}", c, desc, msg, action),
            };
            specs.push(spec);
        }
        for l in d.longs {
            let spec = match d.arg {
                ArgDescr::No(_) => format!("--{}[{}]", l, desc),
                ArgDescr::Req(_) => format!("--{}=[{}]:{}:{}", l, desc, msg, action),
                ArgDescr::Opt(..) => format!("--{}=-[{}]::{}:{}", l, desc, msg, action),
            };
            specs.push(spec);
        }
    }
    let mut s = format!("#compdef {prog}\n# zsh completion for {prog}, generated by `{prog} --completions=zsh`.\n", prog = PROG);
    s.push_str("_arguments -s -S \\\n");
    for spec in specs {
        s.push_str(&format!("  '{}' \\\n", zsh_quote(&spec)));
    }
    s.push_str("  '*:file:_files'\n");
    s
}

/// Escape for a single-quoted fish string.
fn fish_quote(s: &str) -> String {
    s.replace('\\', "\\\\").replace('\'', "\\'")
}

fn fish(opts: &[OptDescr]) -> String {
    let mut s = format!("# fish completion for {prog}, generated by `{prog} --completions=fish`.\n", prog = PROG);
    for d in opts {
        let mut line = format!("complete -c {}", PROG);
        for c in d.shorts.chars() {
            line.push_str(&format!(" -s {}", c));
        }
        for l in d.longs {
            line.push_str(&format!(" -l {}", l));
        }
        line.push_str(&format!(" -d '{}'", fish_quote(d.desc)));
        let required = matches!(d.arg, ArgDescr::Req(_));
        match values_for(d) {
            Values::Words(w) if required => line.push_str(&format!(" -x -a '{}'", w.join(" "))),
            Values::Words(w) => line.push_str(&format!(" -a '{}'", w.join(" "))),
            Values::File if required => line.push_str(" -r -F"),
            Values::Dir if required => line.push_str(" -r -a '(__fish_complete_directories)'"),
            _ if required => line.push_str(" -r"),
            _ => {}
        }
        s.push_str(&line);
        s.push('\n');
    }
    s
}
